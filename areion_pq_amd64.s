	MOVOA X9, X5
	PSRLDQ $8, X5
	PXOR X9, X5
	PCLMULQDQ $0x00, X5, X4
	PXOR X10, X4
	PXOR X11, X4
	MOVOA X4, X5
	PSLLDQ $8, X5
	PXOR X5, X10
	PSRLDQ $8, X4
	PXOR X4, X11

