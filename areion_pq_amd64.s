	MOVQ a+8(FP), BX
	MOVQ b+16(FP), CX
	MOVQ count+24(FP), DX
	MOVQ chi+32(FP), SI

	TESTQ DX, DX
	JLE polymacPCLMULDone

	MOVOU (AX), X0
	MOVOU (SI), X7
	MOVOA X7, X8
	PSRLDQ $8, X8
	PXOR X7, X8

	MOVQ $0x87, DI
	MOVQ DI, X6
	PUNPCKLQDQ X6, X6

