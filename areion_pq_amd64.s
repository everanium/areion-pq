	// 1. Multiply acc (X0) by chi (X7) -> unreduced (X2 = c_low, X3 = c_high)
	MOVOA X0, X2
	PCLMULQDQ $0x00, X7, X2
	MOVOA X0, X3
	PCLMULQDQ $0x11, X7, X3
	MOVOA X0, X4
	PSRLDQ $8, X4
	PXOR X0, X4
	PCLMULQDQ $0x00, X8, X4
	PXOR X2, X4
	PXOR X3, X4
	MOVOA X4, X5
	PSLLDQ $8, X5
	PXOR X5, X2
	PSRLDQ $8, X4
	PXOR X4, X3

	// 2. Multiply a_i (X1) by b_i (X9) -> unreduced (X10 = p00, X11 = p11)
	MOVOU (BX), X1
	MOVOU (CX), X9
	MOVOA X1, X10
	PCLMULQDQ $0x00, X9, X10
	MOVOA X1, X11
	PCLMULQDQ $0x11, X9, X11
	MOVOA X1, X4
	PSRLDQ $8, X4
