	PXOR X11, X3

	MOVOA X3, X4
	PCLMULQDQ $0x11, X6, X4
	MOVOA X4, X5
	PSLLDQ $8, X5
	PXOR X5, X2
	PSRLDQ $8, X4
	PXOR X4, X3

	PCLMULQDQ $0x00, X6, X3
	PXOR X3, X2
	MOVOA X2, X0

	ADDQ $16, BX
	ADDQ $16, CX
	DECQ DX
	JNZ polymacPCLMULLoop

	MOVOU X0, (AX)

