// areionRC4x holds the 10 round constants of P1 replicated 4 times across 64-byte blocks.
var areionRC4x [10 * 64]byte

// areionRC4x2 holds the 10 round constants of P2 replicated 4 times across 64-byte blocks.
var areionRC4x2 [10 * 64]byte

func init() {
	for r := 0; r < 10; r++ {
		for copyIdx := 0; copyIdx < 4; copyIdx++ {
			copy(areionRC4x[r*64+copyIdx*16:r*64+copyIdx*16+16], roundConstantsP1[r][:])
			copy(areionRC4x2[r*64+copyIdx*16:r*64+copyIdx*16+16], roundConstantsP2[r][:])
		}
	}
}
